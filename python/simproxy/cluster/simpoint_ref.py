"""Bit-compatible reimplementation of SimPoint 3.2 clustering.

The reference toolkit uses a dense uniform random projection generated by the
Numerical Recipes ``ran2`` generator, random-sample seeding, and exact-equality
Lloyd convergence. Reproducing those choices lets SimProxy emit the same
simulation points as the reference binary for the same input and seeds.

This module is independent of :mod:`simproxy.cluster.kmeans`; it exists so the
faster Achlioptas backend stays available while validation uses the reference
semantics.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from typing import Any

import numpy as np

from .kmeans import bic_score

__all__ = [
    "DEFAULT_KMEANS_SEED",
    "DEFAULT_PROJECTION_DIM",
    "DEFAULT_PROJECTION_SEED",
    "Ran2",
    "cluster_reference",
    "cluster_reference_range",
    "dense_projection",
    "projection_matrix",
    "sample_init",
]

DEFAULT_PROJECTION_DIM = 15
DEFAULT_PROJECTION_SEED = 2042712918
DEFAULT_KMEANS_SEED = 493575226
DEFAULT_INIT_SEEDS = 5

INT_MAX = 2147483647
IM1 = 2147483563
IM2 = 2147483399
AM = 1.0 / IM1
IMM1 = IM1 - 1
IA1 = 40014
IA2 = 40692
IQ1 = 53668
IQ2 = 52774
IR1 = 12211
IR2 = 3791
NTAB = 32
NDIV = 1 + IMM1 // NTAB
EPS = 1.2e-7
RNMX = 1.0 - EPS


class Ran2:
    """Numerical Recipes ``ran2`` exactly as used by SimPoint's ``Random``."""

    def __init__(self, seed: int = 0) -> None:
        self.state = -seed if seed > 1 else seed
        self.idum2 = 123456789
        self.iy = 0
        self.iv = [0] * NTAB

    def rand_float(self) -> np.float32:
        if self.state <= 0:
            self.state = 1 if -self.state < 1 else -self.state
            self.idum2 = self.state
            for j in range(NTAB + 7, -1, -1):
                k = self.state // IQ1
                self.state = IA1 * (self.state - k * IQ1) - k * IR1
                if self.state < 0:
                    self.state += IM1
                if j < NTAB:
                    self.iv[j] = self.state
            self.iy = self.iv[0]

        k = self.state // IQ1
        self.state = IA1 * (self.state - k * IQ1) - k * IR1
        if self.state < 0:
            self.state += IM1
        k = self.idum2 // IQ2
        self.idum2 = IA2 * (self.idum2 - k * IQ2) - k * IR2
        if self.idum2 < 0:
            self.idum2 += IM2
        j = self.iy // NDIV
        self.iy = self.iv[j] - self.idum2
        self.iv[j] = self.state
        if self.iy < 1:
            self.iy += IMM1
        temp = np.float32(AM * self.iy)
        if float(temp) > RNMX:
            return np.float32(RNMX)
        return temp

    def rand_int(self) -> int:
        return int(np.float32(self.rand_float()) * np.float32(INT_MAX))


def projection_matrix(seed: int, rows: int, cols: int) -> np.ndarray:
    generator = Ran2(seed)
    matrix = np.empty((rows, cols), dtype=np.float64)
    for row in range(rows):
        for col in range(cols):
            matrix[row, col] = float(generator.rand_float()) * 2.0 - 1.0
    return matrix


def dense_projection(matrix: np.ndarray, out_dim: int, seed: int) -> np.ndarray:
    projection = projection_matrix(seed, matrix.shape[1], out_dim)
    return matrix @ projection


def sample_init(matrix: np.ndarray, k: int, seed: int) -> np.ndarray:
    generator = Ran2(seed)
    indices = [generator.rand_int() % matrix.shape[0] for _ in range(k)]
    return matrix[indices].copy()


def _assign(matrix: np.ndarray, centers: np.ndarray) -> np.ndarray:
    diff = matrix[:, None, :] - centers[None, :, :]
    return np.einsum("nkd,nkd->nk", diff, diff).argmin(axis=1)


def _lloyd_exact(
    matrix: np.ndarray, centers: np.ndarray, max_iter: int = 100
) -> tuple[np.ndarray, np.ndarray]:
    centers = centers.copy()
    for _ in range(max_iter):
        labels = _assign(matrix, centers)
        updated = np.zeros_like(centers)
        for cluster_id in range(centers.shape[0]):
            members = matrix[labels == cluster_id]
            if members.size:
                updated[cluster_id] = members.mean(axis=0)
        if np.array_equal(updated, centers):
            centers = updated
            break
        centers = updated
    return _assign(matrix, centers), centers


@dataclass
class ReferenceResult:
    k: int
    labels: np.ndarray
    centers: np.ndarray
    projected: np.ndarray
    bic: float
    representatives: list[int]
    representative_clusters: list[int]
    weights: list[float]
    trials: list[dict[str, Any]] = field(default_factory=list)


def cluster_reference(
    matrix: np.ndarray,
    k: int,
    projection_dim: int = DEFAULT_PROJECTION_DIM,
    projection_seed: int = DEFAULT_PROJECTION_SEED,
    kmeans_seed: int = DEFAULT_KMEANS_SEED,
    num_init_seeds: int = DEFAULT_INIT_SEEDS,
    max_iter: int = 100,
) -> ReferenceResult:
    """Cluster with the reference SimPoint semantics for a fixed ``k``."""
    if matrix.ndim != 2:
        raise ValueError("matrix must be two-dimensional")
    if matrix.shape[0] == 0:
        raise ValueError("cannot cluster an empty matrix")

    projected = dense_projection(matrix, projection_dim, projection_seed)

    best: tuple[float, np.ndarray, np.ndarray, int] | None = None
    trials: list[dict[str, Any]] = []
    for init_index in range(num_init_seeds):
        # SimPoint increments its base seed after every trial and also passes the
        # trial index to ``loadInitialCenters``, so the effective seeds advance
        # by two each time.
        seed = kmeans_seed + 2 * init_index
        centers = sample_init(projected, k, seed)
        labels, centers = _lloyd_exact(projected, centers, max_iter=max_iter)
        score = bic_score(projected, labels, centers)
        trials.append({"k": k, "init_seed": seed, "bic": score})
        if best is None or score > best[0]:
            best = (score, labels, centers, seed)

    assert best is not None
    score, labels, centers, best_seed = best
    representatives: list[int] = []
    representative_clusters: list[int] = []
    for cluster_id in range(k):
        members = np.flatnonzero(labels == cluster_id)
        if members.size == 0:
            continue
        distances = ((projected[members] - centers[cluster_id]) ** 2).sum(axis=1)
        representatives.append(int(members[int(distances.argmin())]))
        representative_clusters.append(cluster_id)
    weights = np.bincount(labels, minlength=k) / matrix.shape[0]
    return ReferenceResult(
        k=k,
        labels=labels,
        centers=centers,
        projected=projected,
        bic=score,
        representatives=representatives,
        representative_clusters=representative_clusters,
        weights=weights.tolist(),
        trials=trials,
    )


def cluster_reference_range(
    matrix: np.ndarray,
    k_min: int = 1,
    k_max: int = 10,
    projection_dim: int = DEFAULT_PROJECTION_DIM,
    projection_seed: int = DEFAULT_PROJECTION_SEED,
    kmeans_seed: int = DEFAULT_KMEANS_SEED,
    num_init_seeds: int = DEFAULT_INIT_SEEDS,
    max_iter: int = 100,
    bic_tolerance: float = 0.9,
) -> tuple[ReferenceResult, list[ReferenceResult]]:
    """Evaluate every ``k`` with reference semantics and apply SimPoint's rule.

    The reference binary uses a binary search over ``k`` when ``-maxK`` is given;
    this helper evaluates the full range, which is slower but selects the same
    threshold rule. Validation against the reference uses a fixed ``k``.
    """
    results: list[ReferenceResult] = []
    base = kmeans_seed
    for k in range(max(1, int(k_min)), int(k_max) + 1):
        results.append(
            cluster_reference(
                matrix,
                k,
                projection_dim=projection_dim,
                projection_seed=projection_seed,
                kmeans_seed=base,
                num_init_seeds=num_init_seeds,
                max_iter=max_iter,
            )
        )
        base += num_init_seeds

    scores = [result.bic for result in results]
    minimum = min(scores)
    threshold = (max(scores) - minimum) * bic_tolerance + minimum
    chosen = next(result for result in results if result.bic >= threshold)
    return chosen, results
