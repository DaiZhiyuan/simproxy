"""Emit a self-contained C program from phase-kernel plans."""

from __future__ import annotations

from .kernels import KernelPlan

__all__ = ["emit_c"]

_HEADER = """/* Generated by SimProxy. Do not edit. */
#include <stdint.h>
#include <stdio.h>

#define MEM_WORDS {words}u
#define MEM_MASK (MEM_WORDS - 1u)

static uint64_t mem[MEM_WORDS];
static volatile uint64_t sink;
"""

_SIMD_TYPEDEF = """
typedef uint32_t u32x4 __attribute__((vector_size(16)));
"""


def _phase_body(index: int, plan: KernelPlan) -> str:
    counts = plan.counts
    lines = [
        f"static void run_phase_{index}(void) {{",
        f"  uint64_t acc = 0x9e3779b97f4a7c15u ^ {plan.seed}u;",
        "  double f = 0.0;",
    ]
    if counts.get("simd", 0):
        lines.append("  u32x4 v = {1u, 2u, 3u, 4u};")
    offset = 0
    for category in ("alu", "mul", "fp", "simd", "load", "store", "branch"):
        count = counts.get(category, 0)
        if count <= 0:
            continue
        offset += 0x1000
        lines.append(f"  for (uint64_t i = 0; i < {count}u; ++i) {{")
        if category == "alu":
            lines.append("    acc = acc * 1664525u + 1013904223u;")
        elif category == "mul":
            lines.append("    acc *= 6364136223846793005u;")
        elif category == "fp":
            lines.append("    f += 1.0 / (double)((i & 31u) + 1u);")
        elif category == "simd":
            lines.append("    v = v * 3u + 1u;")
        elif category == "load":
            lines.append(f"    acc += mem[(i + 0x{offset:x}u) & MEM_MASK];")
        elif category == "store":
            lines.append(f"    mem[(i + 0x{offset:x}u) & MEM_MASK] = acc + i;")
        elif category == "branch":
            lines.append(
                f"    if ((acc % 100u) < {plan.branch_taken_percent}u) acc += 3u; else acc -= 5u;"
            )
        lines.append("  }")
    if counts.get("simd", 0):
        lines.append("  sink += (uint64_t)(v[0] + v[1] + v[2] + v[3]);")
    lines.append("  sink += acc + (uint64_t)f;")
    lines.append("}")
    return "\n".join(lines)


def emit_c(plans: list[KernelPlan], total_instructions: int, source: str = "") -> str:
    words = 1
    if plans:
        words = max(512, plans[0].array_bytes // 8)
        words = 1 << (words - 1).bit_length()

    parts = [_HEADER.format(words=words)]
    if any(plan.counts.get("simd", 0) for plan in plans):
        parts.append(_SIMD_TYPEDEF)
    parts.append(f"/* source: {source} */\n")

    for index, plan in enumerate(plans):
        parts.append(_phase_body(index, plan))

    parts.append("int main(void) {")
    parts.append("  for (uint64_t i = 0; i < MEM_WORDS; ++i) mem[i] = i * 2654435761u;")
    for index in range(len(plans)):
        parts.append(f"  run_phase_{index}();")
    parts.append(
        '  printf("{\\"logical_instructions\\": %llu, \\"phases\\": %d, '
        '\\"sink\\": %llu}\\n",\n'
        f"         (unsigned long long){int(total_instructions)}u, {len(plans)}, "
        "(unsigned long long)sink);"
    )
    parts.append("  return 0;")
    parts.append("}")
    return "\n".join(parts) + "\n"
